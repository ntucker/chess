// Renders Silk, which ships ES modules: the web project's transformIgnorePatterns
// (package.json) lets @reactive through Babel for it.
import { describe, expect, it, jest } from '@jest/globals';
import { SilkProvider } from '@reactive/silk-native';
import { act, type ComponentProps } from 'react';
import { createRoot } from 'react-dom/client';

import type { Note, PositionKey } from '@/lesson/lesson';
import { SAMPLE, uciLine } from '@/lesson/lesson.fixture';
import { lineKeys } from '@/lesson/select';
import type { Playback } from '@/lesson/useLesson';
import { themes } from '@/theme/theme';

import { noNotes, NoteView } from './IdeaCard';

jest.mock('@expo/vector-icons/Ionicons', () => () => null);

(globalThis as { IS_REACT_ACT_ENVIRONMENT?: boolean }).IS_REACT_ACT_ENVIRONMENT = true;

const PLAYBACK: Playback = {
  playable: () => undefined,
  play: () => {},
  goto: () => {},
  stop: () => {},
};

/** Renders a note's view, in the page so its tooltips' layer is too; `unmount` removes it. */
function renderNote(
  props: Partial<ComponentProps<typeof NoteView>> & Pick<ComponentProps<typeof NoteView>, 'shown'>,
) {
  const host = document.createElement('div');
  document.body.append(host);
  const root = createRoot(host);
  act(() =>
    root.render(
      <SilkProvider theme={themes.dark}>
        <NoteView
          lesson={SAMPLE}
          learner="black"
          playback={PLAYBACK}
          pointable={false}
          pointed={false}
          onPoint={() => {}}
          onLeave={() => {}}
          {...props}
        />
      </SilkProvider>,
    ),
  );
  return {
    host,
    unmount: () => {
      act(() => root.unmount());
      host.remove();
    },
  };
}

/** The text a note's view shows and reads aloud. */
function noteText(note: Note): string {
  const { host, unmount } = renderNote({ shown: { note, after: 'after' as PositionKey } });
  const text = host.textContent ?? '';
  unmount();
  return text;
}

describe('NoteView', () => {
  it('credits the model that wrote a generated note', () => {
    expect(
      noteText({ text: 'Your pawn holds d5.', generated: true, model: 'claude-fable-5-2' }),
    ).toContain('Generated by Claude Fable 5.2. No guide explains this move.');
  });

  it('credits no model on a rewritten study comment, which is the study’s analysis', () => {
    const text = noteText({
      text: 'Your pawn holds d5.',
      original: 'c6 prepares d5',
      model: 'claude-sonnet-5-5',
    });
    expect(text).toContain('The study’s words');
    expect(text).not.toContain('Generated by');
  });

  it('credits no model on a note none wrote', () => {
    expect(noteText({ text: 'Your pawn holds d5.', original: 'c6 prepares d5' })).not.toContain(
      'Generated by',
    );
  });

  it('shows a move the note names on a small board when tapped, without pointing at the note', () => {
    const keys = lineKeys(uciLine('e4', 'c6', 'd4', 'd5', 'Nd2'));
    const onPoint = jest.fn();
    const { host, unmount } = renderNote({
      shown: { note: { text: 'Same idea as Nc3.' }, after: keys[5], before: keys[4] },
      pointable: true,
      onPoint,
    });
    const words = [...host.querySelectorAll('div')].find((div) => div.textContent === 'Nc3')!;
    const touch = new Event('pointerup', { bubbles: true });
    Object.assign(touch, { pointerType: 'touch' });
    act(() => {
      words.dispatchEvent(touch);
      const mouse = (type: string, buttons: number) =>
        words.dispatchEvent(new MouseEvent(type, { bubbles: true, button: 0, buttons }));
      mouse('mousedown', 1);
      mouse('mouseup', 0);
      words.click();
    });
    // Every piece of the position after 3.Nc3 stands on the board.
    const tip = document.querySelector('[role="tooltip"]')!;
    expect(tip.querySelectorAll('svg')).toHaveLength(32);
    // A tap on the board, which React bubbles from the tooltip's layer to the note, doesn't point at it either.
    const onBoard = new Event('pointerup', { bubbles: true });
    Object.assign(onBoard, { pointerType: 'touch' });
    act(() => tip.querySelector('svg')!.dispatchEvent(onBoard));
    expect(onPoint).not.toHaveBeenCalled();
    unmount();
  });
});

describe('noNotes', () => {
  it("says a move has no notes, with Stockfish's verdict once there is one", () => {
    expect(noNotes('g6')).toBe('No notes on g6.');
    expect(
      noNotes('g6', {
        quality: 'inaccuracy',
        change: { label: '\u22120.6', description: '0.6 pawns worse for you' },
      }),
    ).toBe('No notes on g6. Stockfish: Inaccuracy, 0.6 pawns worse for you.');
  });
});
